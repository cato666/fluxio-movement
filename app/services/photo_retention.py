"""S11 read-only inventory. No eligibility clock, move, unlink or DB writes.

The approved initial policy is dry-run. Absence of a session reference alone
never authorizes disposal; S16 must establish recoverability before a later
implementation can record orphan observations and quarantine decisions.
"""
from collections import Counter
from pathlib import Path
from sqlalchemy import select
from ..models import TrainingImage, TrainingSession
from ..whatsapp.models import ConversationState, WhatsAppMedia
from ..whatsapp.identity import now
from .training_media import image_directory


def _safe_file(directory, image):
    # Only the normalized UUID filename generated by the existing image store.
    name = f'{image.id}.jpg'
    if image.path != name:
        return 'legacy'
    directory = Path(directory).absolute()
    if any(parent.is_symlink() for parent in (directory, *directory.parents)):
        return 'unsafe_path'
    path = directory / name
    if path.is_symlink():
        return 'unsafe_path'
    if not path.is_file():
        return 'missing'
    return None


def _inventory(session):
    """Return internal IDs/reason codes only; snapshot, never cleanup authority.

    All unexpired non-idle contexts conservatively protect that athlete's
    photos, including undecipherable contexts. No private payload is decrypted.
    A WhatsAppMedia reference is retained even after its TTL has expired.
    Live shared weeks derive images from sessions already protected here.
    """
    directory = image_directory()
    referenced = set(session.scalars(select(TrainingSession.source_image_id).where(
        TrainingSession.source_image_id.is_not(None))))
    media = {(row.athlete_id, row.path) for row in session.scalars(select(WhatsAppMedia))}
    contexts = set(session.scalars(select(ConversationState.athlete_id).where(
        ConversationState.state != 'IDLE', ConversationState.expires_at > now())))
    items = []
    with session.no_autoflush:
        for image in session.scalars(select(TrainingImage).order_by(TrainingImage.id)):
            reason = _safe_file(directory, image)
            if reason is None:
                if image.id in referenced:
                    reason = 'session_reference'
                elif image.athlete_id in contexts:
                    reason = 'active_context'
                elif (image.athlete_id, 'training-images/' + image.path) in media:
                    reason = 'media_reference'
                else:
                    reason = 'unreferenced_observation'
            items.append({'image_id': str(image.id), 'reason': reason})
    return {'mode': 'dry_run', 'effective_cleanup': 'BLOCKED_S16',
            'eligible_for_deletion': 0, 'counts': dict(Counter(x['reason'] for x in items)),
            'items': items}


def inventory(session):
    with session.no_autoflush:
        return _inventory(session)
